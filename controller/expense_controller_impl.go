type ExpenseControllerImpl struct {
	Service service.ExpenseService
}

func NewExpenseControllerImpl(service service.ExpenseService) ExpenseController {
	return &ExpenseControllerImpl{Service: service}
}

/*
Body for create and edit

	{
		"expense_id": 1,                // edit only
		"store_id": null,               // null = whole business
		"expense_category_id": null,    // null = uncategorized
		"amount": 150000,
		"description": "Electricity November",
		"expense_date": 1763683200,     // epoch seconds, null = now
		"payment_type": "CASH"          // empty = CASH
	}
*/
type ExpenseControllerRequestBody struct {
	ExpenseId         int               `json:"expense_id"`
	StoreId           *int              `json:"store_id"`
	ExpenseCategoryId *int              `json:"expense_category_id"`
	Amount            int               `json:"amount"`
	Description       string            `json:"description"`
	ExpenseDate       *int64            `json:"expense_date"`
	PaymentType       model.PaymentType `json:"payment_type"`
}

func (body *ExpenseControllerRequestBody) toExpense(tenantId int) *model.Expense {
	expense := &model.Expense{
		Id:                body.ExpenseId,
		TenantId:          tenantId,
		StoreId:           body.StoreId,
		ExpenseCategoryId: body.ExpenseCategoryId,
		Amount:            body.Amount,
		Description:       body.Description,
		PaymentType:       body.PaymentType,
	}
	if body.ExpenseDate != nil {
		expense.ExpenseDate = time.Unix(*body.ExpenseDate, 0)
	}

	return expense
}

type ExpenseControllerGetRequest struct {
	StoreId           int                  `json:"store_id"`            // 0 = all, -1 = only whole business
	ExpenseCategoryId int                  `json:"expense_category_id"` // 0 = all, -1 = uncategorized
	Limit             int                  `json:"limit"`
	Page              int                  `json:"page"`
	Filters           []*query.QueryFilter `json:"filters"`
	DateFilter        *query.DateFilter    `json:"date_filter"`
}

func badRequest(ctx *fiber.Ctx, message string) error {
	return ctx.Status(fiber.StatusBadRequest).
		JSON(common.NewWebResponseError(400, common.StatusError, message))
}

const malformedBodyMessage = "Something gone wrong ! The request body is malformed"

// Create implements ExpenseController.
func (controller *ExpenseControllerImpl) Create(ctx *fiber.Ctx) error {
	// It's guaranteed to be int, because restrict by tenant already did check first
	tenantId, _ := strconv.Atoi(ctx.Params("tenantId"))

	userId, ok := ctx.Locals("sub").(int)
	if !ok {
		return badRequest(ctx, "Unexpected behavior ! could not get the id")
	}

	var body ExpenseControllerRequestBody
	if err := ctx.BodyParser(&body); err != nil {
		return badRequest(ctx, malformedBodyMessage)
	}

	expense := body.toExpense(tenantId)
	expense.Id = 0 // id is generated by DB
	expense.ResponsibleUserId = userId

	createdExpense, err := controller.Service.Create(expense)
	if err != nil {
		return badRequest(ctx, err.Error())
	}

	return ctx.Status(fiber.StatusOK).
		JSON(common.NewWebResponse(200, common.StatusSuccess, fiber.Map{
			"created_expense": createdExpense,
		}))
}

// Get implements ExpenseController.
func (controller *ExpenseControllerImpl) Get(ctx *fiber.Ctx) error {
	tenantId, _ := strconv.Atoi(ctx.Params("tenantId"))

	var body ExpenseControllerGetRequest
	if err := ctx.BodyParser(&body); err != nil {
		return badRequest(ctx, malformedBodyMessage)
	}

	expenses, count, sumAmount, err := controller.Service.Get(tenantId, body.StoreId, body.ExpenseCategoryId, body.Limit, body.Page, body.Filters, body.DateFilter)
	if err != nil {
		return badRequest(ctx, err.Error())
	}

	return ctx.Status(fiber.StatusOK).
		JSON(common.NewWebResponse(200, common.StatusSuccess, fiber.Map{
			"expenses":               expenses,
			"total_count":            count,
			"sum_amount":             sumAmount, // all matched rows, not only this page
			"page":                   body.Page,
			"limit":                  body.Limit,
			"requested_by_tenant_id": tenantId,
		}))
}

// FindById implements ExpenseController.
func (controller *ExpenseControllerImpl) FindById(ctx *fiber.Ctx) error {
	tenantId, _ := strconv.Atoi(ctx.Params("tenantId"))

	rawExpenseId := ctx.Query("expense_id", "")
	expenseId, err := strconv.Atoi(rawExpenseId)
	if err != nil {
		return badRequest(ctx, fmt.Sprintf("Error while get expense_id, given expense_id = %s", rawExpenseId))
	}

	expense, err := controller.Service.FindById(tenantId, expenseId)
	if err != nil {
		return badRequest(ctx, err.Error())
	}

	return ctx.Status(fiber.StatusOK).
		JSON(common.NewWebResponse(200, common.StatusSuccess, fiber.Map{
			"expense": expense,
		}))
}

